'use client';

import type { MeetingSummary } from '@/lib/types';

export function summaryToMarkdown(s: MeetingSummary, title: string) {
  const list = (a?: string[]) => (a && a.length ? a.map((x) => `- ${x}`).join('\n') : '- None');
  const out: string[] = [`# ${title}`, '', '## Summary', s.summary || '', '', '## Key points', list(s.keyPoints), ''];
  if (s.decisions?.length) out.push('## Decisions', list(s.decisions), '');
  if (s.actionItems?.length) out.push('## Action items', s.actionItems.map((a) => `- ${a.task}${a.owner ? ` (${a.owner})` : ''}`).join('\n'), '');
  if (s.people?.length) {
    out.push('## People');
    s.people.forEach((p) => {
      out.push('', `### ${p.name}`, p.summary || '');
      if (p.experience) out.push('', '**Experience**', p.experience);
      if (p.answers?.length) {
        out.push('', `**Answers${typeof p.accuracy === 'number' ? ` (${Math.round(p.accuracy)}% correct)` : ''}**`);
        p.answers.forEach((a) => out.push(`- ${a.question} - ${a.verdict}: ${a.answer}${a.correction ? ` Correction: ${a.correction}` : ''}`));
      }
      if (p.strengths?.length) out.push('', '**Strengths**', list(p.strengths));
      if (p.concerns?.length) out.push('', '**Concerns**', list(p.concerns));
      if (p.scores?.length) out.push('', '**Suggested scores (1-5)**', p.scores.map((x) => `- ${x.criterion}: ${x.score} - ${x.reason}`).join('\n'));
      if (p.quotes?.length) out.push('', '**Quotes**', p.quotes.map((q) => `> ${q}`).join('\n'));
    });
    out.push('');
  }
  if (s.followUps?.length) out.push('## Follow-ups', list(s.followUps), '');
  out.push('_Generated by Dense Meet AI from a speech-to-text transcript. Scores and notes are suggestions for the host and may contain errors._');
  return out.join('\n');
}

function Bullets({ items }: { items?: string[] }) {
  if (!items || !items.length) return null;
  return (
    <ul className="bullets">
      {items.map((x, i) => (
        <li key={i}>{x}</li>
      ))}
    </ul>
  );
}

export default function SummaryView({ s }: { s: MeetingSummary }) {
  return (
    <div className="summary">
      <p className="summary-lead">{s.summary}</p>

      {s.keyPoints?.length > 0 && (
        <>
          <h4>Key points</h4>
          <Bullets items={s.keyPoints} />
        </>
      )}
      {s.decisions?.length > 0 && (
        <>
          <h4>Decisions</h4>
          <Bullets items={s.decisions} />
        </>
      )}
      {s.actionItems?.length > 0 && (
        <>
          <h4>Action items</h4>
          <ul className="bullets">
            {s.actionItems.map((a, i) => (
              <li key={i}>
                {a.task}
                {a.owner ? <span className="muted"> ({a.owner})</span> : null}
              </li>
            ))}
          </ul>
        </>
      )}

      {s.people?.map((p, i) => (
        <div key={i} className="person-card">
          <strong>{p.name}</strong>
          <p>{p.summary}</p>
          {p.experience && (
            <>
              <h5>Experience</h5>
              <p>{p.experience}</p>
            </>
          )}
          {p.answers && p.answers.length > 0 && (
            <>
              <h5>
                Answers {typeof p.accuracy === 'number' && <span className="muted">· {Math.round(p.accuracy)}% correct</span>}
              </h5>
              {typeof p.accuracy === 'number' && (
                <div className="accbar" aria-label={`${Math.round(p.accuracy)} percent correct`}>
                  <i style={{ width: `${Math.max(0, Math.min(100, p.accuracy))}%` }} />
                </div>
              )}
              <div className="answers">
                {p.answers.map((a, k) => (
                  <div key={k} className={`answer ${a.verdict}`}>
                    <div className="q">{a.question}</div>
                    <div className="muted">{a.answer}</div>
                    {a.correction && <div className="fix">Correction: {a.correction}</div>}
                  </div>
                ))}
              </div>
            </>
          )}
          {p.scores?.length > 0 && (
            <div className="scores">
              {p.scores.map((sc, j) => (
                <div key={j} className="score-row" title={sc.reason}>
                  <span>{sc.criterion}</span>
                  <i>
                    <b style={{ width: `${Math.max(0, Math.min(5, Number(sc.score) || 0)) * 20}%` }} />
                  </i>
                  <span className="score-num">{Number(sc.score).toFixed(1)}</span>
                </div>
              ))}
              <div className="muted tiny">AI suggestion for the host. Tap a row to see why.</div>
            </div>
          )}
          {p.strengths?.length > 0 && (
            <>
              <h5>Strengths</h5>
              <Bullets items={p.strengths} />
            </>
          )}
          {p.concerns?.length > 0 && (
            <>
              <h5>To probe</h5>
              <Bullets items={p.concerns} />
            </>
          )}
          {p.quotes?.length > 0 && (
            <>
              <h5>Quotes</h5>
              {p.quotes.map((q, k) => (
                <blockquote key={k}>{q}</blockquote>
              ))}
            </>
          )}
        </div>
      ))}

      {s.followUps?.length > 0 && (
        <>
          <h4>Follow-ups</h4>
          <Bullets items={s.followUps} />
        </>
      )}
    </div>
  );
}
